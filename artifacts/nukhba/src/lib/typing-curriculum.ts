export type Section = {
  index: number;
  title: string;
  subtitle: string;
  newKeys: string[];
  color: string;
  bgColor: string;
  emoji: string;
  lessons: Lesson[];
};

type RawLesson = [string, string, number?];

function buildSection(
  index: number,
  title: string,
  subtitle: string,
  newKeys: string[],
  color: string,
  bgColor: string,
  emoji: string,
  rawLessons: RawLesson[],
): Section {
  const lessons: Lesson[] = rawLessons.map(([t, text, wpm], li) => ({
    id: 0,
    sectionIndex: index,
    lessonIndex: li,
    title: t,
    text,
    targetWpm: wpm ?? 20 + index * 2,
    targetAccuracy: 90,
  }));
  return { index, title, subtitle, newKeys, color, bgColor, emoji, lessons };
}

