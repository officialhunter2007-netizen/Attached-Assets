export type Section = {
  index: number;
  title: string;
  subtitle: string;
  newKeys: string[];
  color: string;
  bgColor: string;
  emoji: string;
  lessons: Lesson[];
};

type RawLesson = [string, string, number?];

const SECTION_DEFAULT_WPM = [12, 25, 36, 45, 55, 20, 23, 60, 60, 66, 72, 55, 60, 40];

function buildSection(
  index: number, title: string, subtitle: string, newKeys: string[],
  color: string, bgColor: string, emoji: string, rawLessons: RawLesson[],
): Section {
  const def = SECTION_DEFAULT_WPM[index] ?? 30;
  const lessons: Lesson[] = rawLessons.map(([t, text, wpm], li) => ({
    id: 0, sectionIndex: index, lessonIndex: li, title: t, text,
    targetWpm: wpm ?? def, targetAccuracy: 90,
  }));
  return { index, title, subtitle, newKeys, color, bgColor, emoji, lessons };
}

