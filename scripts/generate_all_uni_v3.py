    global CONCEPT_CACHE, MISTAKE_CACHE
    if slug not in CONCEPT_CACHE:
        CONCEPT_CACHE[slug] = get_concepts_bank(slug)
    if slug not in MISTAKE_CACHE:
        MISTAKE_CACHE[slug] = get_mistakes_bank(slug)

    concepts_all = CONCEPT_CACHE[slug]
    mistakes_all = MISTAKE_CACHE[slug]

    lessons = []
    prev_topic = "المفاهيم الأساسية السابقة"
    for li in range(1, n + 1):
        topic = unit_concepts[li % len(unit_concepts)] if unit_concepts else f"مفهوم متقدم {li} في {unit_name}"
        hh = _h(f"{unit_code}_{li}_{topic}_{seed_h}")

        nc = 2 + (hh % 2)  # 2-3 concepts per lesson
        lconcepts = []
        used_names = set()
        for ci in range(nc):
            ch = _h(f"{unit_code}_{li}_{ci}_concept_{seed_h}")
