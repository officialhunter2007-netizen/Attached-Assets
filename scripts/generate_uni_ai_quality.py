def make_bridge(prev_topic, current_topic):
    bridges = [
        f"الآن وقد أتقنتَ {prev_topic}، حان الوقت لنرتقي إلى المستوى التالي. سننتقل اليوم إلى {current_topic} — المهارة التي ستبني على كل ما تعلمته وتضيف بُعداً جديداً لقدراتك. اربط حزامك، سنتعمق أكثر.",
        f"في الدرس السابق، فككنا {prev_topic} وعرفنا أسراره. اليوم سنبني على تلك المعرفة ونتعلم {current_topic} — الأداة التي يستخدمها المحترفون يومياً في مشاريع الذكاء الاصطناعي الحقيقية.",
        f"بعد أن فهمت {prev_topic}، لاحظتَ أن هناك فجوة — شيء ما ناقص. هذا 'الشيء' هو بالضبط {current_topic}، وسنسد هذه الفجوة اليوم. ما ستتعلمه الآن هو الفارق بين من 'يعرف' ومن 'يتقن'.",
        f"مبروك! قطعتَ شوطاً مهماً في رحلتك مع {prev_topic}. لكن رحلة المحترف لا تتوقف. اليوم سنفتح معاً باب {current_topic} — واحد من أكثر المواضيع التي ستستخدمها في حياتك العملية.",
        f"كل مفهوم جديد في الذكاء الاصطناعي يبني على ما سبقه — مثل مكعبات الليغو، كل قطعة تزيد البناء قوة وارتفاعاً. {prev_topic} كان قطعة أساسية. اليوم، {current_topic} هي القطعة التالية.",
    ]
    return bridges[_h(prev_topic + current_topic) % len(bridges)]

