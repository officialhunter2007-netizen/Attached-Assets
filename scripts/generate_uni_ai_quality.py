def generate_lessons(unit_code, unit_name, stage_name, slug, n=10):
    lessons = []
    prev_topic = "المفاهيم الأساسية"
    
    for li in range(1, n+1):
        seed = _h(f"{unit_code}_{li}")
        used_names = set()
        
        n_concepts = 3 + (seed % 3)
        lconcepts = []
        for ci in range(n_concepts):
            for attempt in range(100):
                idx = (_h(f"{unit_code}_{li}_{ci}_{attempt}")) % len(CONCEPTS)
                c_name, c_expl = CONCEPTS[idx]
                short_name = c_name.split(":")[0].strip()
                if short_name not in used_names:
                    used_names.add(short_name)
                    break
            else:
                # Fallback: pick any unused concept
                for idx in range(len(CONCEPTS)):
                    c_name, c_expl = CONCEPTS[idx]
                    short_name = c_name.split(":")[0].strip()
                    if short_name not in used_names:
                        used_names.add(short_name)
                        break
                else:
                    c_name, c_expl = CONCEPTS[0]
                    used_names.add(c_name.split(":")[0].strip())
            lconcepts.append({
                "name": c_name,
                "explanation": c_expl,
                "mastery_criterion": f"يشرح الطالب {short_name} بأسلوبه الخاص ويعطي مثالاً عملياً بالكود",
                "weight": 2 if ci == 0 else 1
            })
        
        n_mistakes = 2 + (seed % 2)
        lmistakes = []
        used_m = set()
        for mi in range(n_mistakes):
            idx = (_h(f"{unit_code}_{li}_{mi}")) % len(MISTAKES)
            m = MISTAKES[idx]
            m_title = m[0][:30]
            if m_title not in used_m:
                used_m.add(m_title)
                lmistakes.append({
                    "mistake": f"{m[0]}\n{m[1]}",
                    "correction": m[2],
                    "treatment": m[3],
                    "severity": m[4]
                })
        
        lesson_title = lconcepts[0]["name"].split(":")[0].strip()
        
        lessons.append({
            "lesson_index": li,
            "name": lesson_title,
            "goal": f"فهم وتطبيق {lesson_title} عملياً — بنهاية الدرس ستكون قادراً على شرحه وكتابة الكود الخاص به",
            "bridge_sentence": make_bridge(prev_topic, lesson_title),
            "prerequisite_lessons": [] if li == 1 else [f"{unit_code}.{li-1}"],
            "enables_lessons": [] if li == n else [f"{unit_code}.{li+1}"],
            "final_check_question": f"اشرح بكلماتك: ما هو {lesson_title}؟ واكتب كود Python بسيطاً يوضح كيفية استخدامه. ما أشهر خطأ يجب تجنبه عند استخدامه؟",
            "session_complete_criterion": f"يشرح الطالب {lesson_title} بوضوح ويكتب كوداً عملياً يطبق المفهوم",
            "yemeni_examples": [f"تطبيق عملي لـ {lesson_title}: اكتب كوداً يستخدم هذا المفهوم في سيناريو حقيقي."],
            "expected_duration_minutes": 30,
            "estimated_gem_cost": 90,
            "solution_outline": make_solution(lesson_title),
            "motivation_hook": make_motivation(lesson_title),
            "learning_objectives": [
                {"statement": f"يفهم الطالب {lesson_title}", "bloom_level": "understand"},
                {"statement": f"يطبق الطالب {lesson_title} عملياً بالكود", "bloom_level": "apply"}
            ],
            "glossary": [],
            "concepts": lconcepts,
            "common_mistakes": lmistakes
        })
        prev_topic = lesson_title
    return lessons

