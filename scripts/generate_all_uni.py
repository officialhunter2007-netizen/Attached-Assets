def generate_specialty(slug):
    if slug not in SPECS:
        print(f"❌ تخصص غير معروف: {slug}")
        return None

    spec = SPECS[slug]
    out_dir = Path(f"out/{slug}")
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"\n{'='*60}")
    print(f"توليد: {spec['name']} ({slug})")
    print(f"{'='*60}")

    # بناء التخصص
    specialty = {
        "slug": slug,
        "name": spec["name"],
        "description": spec["desc"],
        "scope": spec["scope"],
        "language": "ar",
        "region": "YE",
        "icon": spec["icon"],
        "target_persona": spec["persona"],
        "teacher_tone": spec["tone"],
        "yemeni_examples": [
            f"تطبيق {spec['name']} في {c}" for c in YEMENI_CONTEXTS[:5]
        ],
        "allowed_viz_templates": spec["viz"],
        "allowed_tools": spec["tools"],
        "glossary": spec.get("glossary", [])
    }

    levels = []
    all_unit_codes = []
    all_stage_codes = []

    for li, (l_name, l_goal, l_bloom) in enumerate(spec["levels"]):
        level_idx = li + 1
        stages = []

        for si in range(7):
            s_idx = si + 1
            stage_code = f"{level_idx}.{s_idx}"
            all_stage_codes.append(stage_code)
            s_template = STAGE_TEMPLATES[si]
            s_name = f"{s_template[0]} — {l_name.split(':')[1].strip() if ':' in l_name else l_name}"
            s_goal = f"{s_template[1]} في سياق {l_name}"

            units = []
            for ui in range(9):
                u_idx = ui + 1
                unit_code = f"{stage_code}.{u_idx}"
                all_unit_codes.append(unit_code)
                u_template = UNIT_TEMPLATES[ui % len(UNIT_TEMPLATES)]
                u_name = u_template[0].format(topic=f"المحور {u_idx}", specialty=spec['name'])
                u_goal = u_template[1].format(topic=f"المحور {u_idx}", specialty=spec['name'])
                u_concepts = [c.format(topic=f"م{u_idx}", specialty=spec['name']) for c in u_template[2]]

                # شرط المتطلبات
                prereq_units = []
                enables_units = []
                if ui > 0:
                    prereq_units.append(f"{stage_code}.{ui}")
                if ui < 8:
                    enables_units.append(f"{stage_code}.{ui+2}")

                print(f"  الوحدة {unit_code}: {u_name[:50]}...")

                # توليد الدروس والمعامل
                lessons = generate_lessons(unit_code, u_name, u_goal, u_concepts, s_name, slug)
                labs = generate_labs(unit_code, u_name, u_concepts, len(lessons), slug)

                unit = {
                    "unit_index": u_idx,
                    "name": u_name,
                    "goal": u_goal,
                    "prerequisite_units": prereq_units,
                    "enables_units": enables_units,
                    "key_concepts": u_concepts[:5],
                    "motivation_hook": f"في هذه الوحدة، ستكتسب مهارة أساسية في {spec['name']} تمكّنك من العمل بكفاءة في {_pick(YEMENI_CONTEXTS, ui % len(YEMENI_CONTEXTS))}",
                    "learning_objectives": [
                        {"statement": f"أن يطبق الطالب {c} في سياق عملي يمني", "bloom_level": "apply"}
                        for c in u_concepts[:3]
                    ],
                    "lessons": lessons,
                    "labs": labs,
                    "exam": {"pass_threshold_percent": 60, "points": 10, "time_limit_minutes": 30}
                }
                units.append(unit)

            stage = {
                "stage_index": s_idx,
                "name": s_name,
                "goal": s_goal,
                "bloom_focus": l_bloom,
                "units": units,
                "exam": {"pass_threshold_percent": 60, "points": 20, "time_limit_minutes": 45}
            }
            stages.append(stage)

        level = {
            "level_index": level_idx,
            "name": l_name,
            "goal": l_goal,
            "bloom_focus": l_bloom,
            "stages": stages,
            "exam": {"pass_threshold_percent": 60, "points": 50, "time_limit_minutes": 90}
        }
        levels.append(level)

    # بنوك الامتحانات
    print("  توليد بنوك الامتحانات...")
    unit_banks = {}
    for code in all_unit_codes:
        unit_banks[code] = generate_exam_bank(code, "unit", 10)
    stage_banks = {}
    for code in all_stage_codes:
        stage_banks[code] = generate_exam_bank(code, "stage", 15)
    level_banks = {}
    for i in range(1, 6):
        level_banks[str(i)] = generate_exam_bank(str(i), "level", 20)

    # اختبار التحديد
    placement = generate_placement_test(slug)

    # التجميع النهائي
    final = {
        "schema_version": "v4.1",
        "specialty": specialty,
        "levels": levels,
        "exam_banks": {
            "unit_banks": unit_banks,
            "stage_banks": stage_banks,
            "level_banks": level_banks
        },
        "placement_test_questions": placement,
        "publish_notes": f"منهج {spec['name']} v4.1 — 5 مستويات — تم التوليد برمجياً."
    }

    out_path = out_dir / "final.json"
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(final, f, ensure_ascii=False, indent=2)

    size_mb = out_path.stat().st_size / (1024 * 1024)
    print(f"\n✅ {spec['name']}: {size_mb:.1f} MB | مستويات={len(levels)} وحدات={len(all_unit_codes)} دروس={sum(1 for l in levels for s in l['stages'] for u in s['units'] for _ in u['lessons'])}")
    return out_path


