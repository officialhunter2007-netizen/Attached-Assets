def generate_lessons(unit_code, unit_name, unit_goal, key_concepts, stage_name, slug, lesson_count=10):
    lessons = []
    prev = "أساسيات المجال"
    concepts_all = get_specialty_concepts(slug)
    mistakes_all = get_specialty_mistakes(slug)
    spec = SPECS[slug]

    for li in range(1, lesson_count + 1):
        topic = key_concepts[li % len(key_concepts)] if key_concepts else f"مفهوم {li}"

        # اختيار 3-5 مفاهيم
        n_concepts = 3 + (_hash_int(topic + str(li)) % 3)
        lesson_concepts = []
        for ci in range(n_concepts):
            c_name, c_expl = concepts_all[(_hash_int(topic + str(ci))) % len(concepts_all)]
            lesson_concepts.append({
                "name": f"{c_name} — {topic} (محور {ci+1})",
                "explanation": f"{c_expl} في سياق {spec['name']} وتحديداً {unit_name}، هذا المفهوم أساسي لأنه يمكننا من التعامل مع التحديات الحقيقية التي تواجه المختصين في {_pick(YEMENI_CITIES, ci)}.",
                "mastery_criterion": f"الطالب يشرح {c_name} بأسلوبه ويطبقه على سيناريو في {_pick(YEMENI_CONTEXTS, ci)}",
                "weight": 2 if ci == 0 else 1
            })

        # اختيار 2-3 أخطاء
        n_mistakes = 2 + (_hash_int(topic + str(li)) % 2)
        lesson_mistakes = []
        for mi in range(n_mistakes):
            m_title, m_mistake, m_corr, m_treat, m_sev = mistakes_all[(_hash_int(topic + str(mi))) % len(mistakes_all)]
            lesson_mistakes.append({
                "mistake": f"{m_title}\n{m_mistake}",
                "correction": m_corr,
                "treatment": m_treat,
                "severity": m_sev
            })

        lesson = {
            "lesson_index": li,
            "name": f"الدرس {li}: {unit_name} — {topic}",
            "goal": f"إتقان {topic} وتطبيقه عملياً في سياق {unit_name}",
            "bridge_sentence": make_bridge(prev, topic, unit_name, slug),
            "prerequisite_lessons": [] if li == 1 else [f"{unit_code}.{li-1}"],
            "enables_lessons": [] if li == lesson_count else [f"{unit_code}.{li+1}"],
            "final_check_question": get_specialty_final_check(slug, topic, li),
            "session_complete_criterion": f"الطالب يفهم {topic} ويستطيع تطبيقه على سيناريو عملي في {spec['name']} ويشرح خطواته بوضوح",
            "yemeni_examples": get_specialty_examples(slug, li),
            "expected_duration_minutes": 25 + (li % 3) * 5,
            "estimated_gem_cost": 80 + (li % 5) * 5,
            "solution_outline": get_specialty_solution(slug, topic, li),
            "motivation_hook": make_motivation(topic, unit_name, slug),
            "learning_objectives": [
                {"statement": f"أن يفهم الطالب {c['name']} ويشرحه بأسلوبه", "bloom_level": "understand"}
                for c in lesson_concepts[:2]
            ],
            "glossary": [
                {"term": t["term"], "definition": t["definition"]}
                for t in spec.get("glossary", [])
                if _hash_int(topic + t["term"]) % 3 == 0
            ][:2],
            "concepts": lesson_concepts,
            "common_mistakes": lesson_mistakes
        }
        lessons.append(lesson)
        prev = topic
    return lessons

