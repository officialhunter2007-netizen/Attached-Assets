def pick_concept():
    c_idx = random.randint(0, len(CONCEPTS)-1)
    return list(CONCEPTS.values())[c_idx]

def pick_mistake():
    return MISTAKES[random.randint(0, len(MISTAKES)-1)]

def generate_lessons(unit_code, unit_name, stage_name, slug, n=10):
    lessons = []
    prev_topic = "أساسيات هذا المجال"
    
    for li in range(1, n+1):
        seed = _h(f"{unit_code}_{li}")
        used_concepts = set()  # per-lesson dedup only
        used_mistakes = set()  # per-lesson dedup only
        
        # اختر 3-5 مفاهيم فريدة
        n_concepts = 3 + (seed % 3)
        lconcepts = []
        attempts = 0
        while len(lconcepts) < n_concepts and attempts < 50:
            attempts += 1
            c_name, c_expl = pick_concept()
            if c_name not in used_concepts:
                used_concepts.add(c_name)
                lconcepts.append({
                    "name": c_name,
                    "explanation": c_expl,
                    "mastery_criterion": f"يشرح الطالب {c_name.split(':')[0]} بأسلوبه الخاص ويعطي مثالاً عملياً من خبرته",
                    "weight": 2 if len(lconcepts) == 0 else 1
                })
        
        # اختر 2-3 أخطاء فريدة
        n_mistakes = 2 + (seed % 2)
        lmistakes = []
        attempts = 0
        while len(lmistakes) < n_mistakes and attempts < 50:
            attempts += 1
            m = pick_mistake()
            m_title = m[0][:40]
            if m_title not in used_mistakes:
                used_mistakes.add(m_title)
                lmistakes.append({
                    "mistake": f"{m[0]}\n{m[1]}",
                    "correction": m[2],
                    "treatment": m[3],
                    "severity": m[4]
                })
        
        topic = unit_name.split(":")[-1].strip() if ":" in unit_name else unit_name[:30]
        # Use the first concept name to give each lesson a unique, descriptive title
        lesson_title = lconcepts[0]["name"].split(":")[0].strip() if lconcepts else topic
        lesson_name = f"{lesson_title}"
        if len(lesson_name) < 20 and li > 1:
            lesson_name = f"{lesson_title}: {topic[:40]}"
        
        lessons.append({
            "lesson_index": li,
            "name": lesson_name,
            "goal": f"فهم وتطبيق {lesson_title} عملياً — بنهاية الدرس ستكون قادراً على شرحه وتطبيقه",
            "bridge_sentence": make_bridge(prev_topic, topic),
            "prerequisite_lessons": [] if li == 1 else [f"{unit_code}.{li-1}"],
            "enables_lessons": [] if li == n else [f"{unit_code}.{li+1}"],
            "final_check_question": f"اشرح بكلماتك: ما هو {topic}؟ وكيف ستستخدمه في مشروعك القادم؟ أعطِ مثالاً عملياً محدداً.",
            "session_complete_criterion": f"يشرح الطالب {topic} بوضوح ويطبقه عملياً على مثال من اختياره",
            "yemeni_examples": [
                f"تخيّل أنك مسؤول تقنية المعلومات في مؤسسة، وتحتاج لتطبيق {topic} في بيئة العمل. صف الخطوات العملية التي ستتخذها."
            ],
            "expected_duration_minutes": 30,
            "estimated_gem_cost": 90,
            "solution_outline": make_solution(topic),
            "motivation_hook": make_motivation(topic),
            "learning_objectives": [
                {"statement": f"يفهم الطالب مفهوم {topic}", "bloom_level": "understand"},
                {"statement": f"يطبق الطالب {topic} عملياً", "bloom_level": "apply"}
            ],
            "glossary": [],
            "concepts": lconcepts,
            "common_mistakes": lmistakes
        })
        prev_topic = topic
    return lessons

