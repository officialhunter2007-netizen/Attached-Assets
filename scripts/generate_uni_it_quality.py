        for si, stage in enumerate(level["stages"]):
            s_idx = si + 1
            stage_code = f"{level_idx}.{s_idx}"
            all_stage_codes.append(stage_code)
            result_units = []
            
            for ui, u_name in enumerate(stage["units"]):
                u_idx = ui + 1
